#pragma once

#include <map>
#include <string>
#include <any>

/**
 * @class IWrapper
 * @brief Интерфейс для обёрток метода класса.
 * 
 * IWrapper представляет собой абстрактный интерфейс, определяющий контракт
 * для обёрток, которые позволяют выполнять методы класса через единый интерфейс.
 * Основная идея — скрыть типовую информацию о методе и параметрах, позволяя
 * передавать параметры как std::any и получать результаты того же типа.
 * 
 * Производные классы обязаны реализовать:
 * - метод execute() для выполнения обёрнутого метода с переданными аргументами
 * 
 * @see Wrapper для конкретной реализации этого интерфейса
 */
class IWrapper {
public:
    /**
     * @brief Виртуальный деструктор по умолчанию.
     * 
     * Обеспечивает корректное удаление производных классов через указатель на базовый класс.
     */
    virtual ~IWrapper() = default;
    
    /**
     * @brief Выполняет обёрнутый метод с переданными аргументами.
     * 
     * @param args Map, где ключи — имена параметров, значения — параметры типа std::any.
     * 
     * @return std::any Результат выполнения метода, упакованный в std::any.
     *         Для методов, возвращающих void, возвращается пустой std::any.
     * 
     * @throws std::invalid_argument Если переданы неправильные аргументы
     *         (неправильный тип, отсутствующий параметр и т.д.)
     * 
     * @note Реализация должна отвечать за проверку типов и преобразование аргументов
     *       из std::any в нужные типы, а также упаковку результата обратно в std::any.
     */
    virtual std::any execute(std::map<std::string, std::any> const& args) = 0;
};

